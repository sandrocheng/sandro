"""
演示type()函数的使用
"""
age = 18
score = 7.5
gender = '男'
name = "jack"
isPass = True

print(f"age的类型是：{type(age)}")  # <class 'int'>
print(f"score的类型是：{type(score)}")  # <class 'float'>
print(f"gender的类型是： {type(gender)}")  # <class 'str'>
print(f"name的类型是： {type(name)}")  # <class 'str'>
print(f"isPass的类型是：{type(isPass)}")  # <class 'bool'>
print(f"False的类型是： {type(False)}")  # <class 'bool'>
